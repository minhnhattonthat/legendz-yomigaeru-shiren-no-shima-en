"""Write tools/debug/partner.lua: the RAM writes the game's own Reborn makes, as {addr, "hex"} runs, diffed from two dumps of the save
struct (docs/re/doll.md). Dumps come from tools/lua/dumpram.lua: before Reborn, and after the Legendz is named.

    python -X utf8 tools/debug/capture_partner.py work/qa/d0/ram.bin work/qa/d3/ram.bin
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EWRAM = 0x02000000
STRUCT = 0x36A30  # save struct offset in EWRAM
SIZE = 0x4200
SKIP = range(0, 0x100)  # the story flags: scenes set their own


def runs(a, b, gap=8):
    out, start, end = [], None, None
    for i in range(STRUCT, STRUCT + SIZE):
        if a[i] != b[i] and i - STRUCT not in SKIP:
            if start is None or i > end + gap:
                if start is not None:
                    out.append((start, end))
                start = i
            end = i
    if start is not None:
        out.append((start, end))
    return out


def main():
    a, b = Path(sys.argv[1]).read_bytes(), Path(sys.argv[2]).read_bytes()
    lines = ["-- Generated by capture_partner.py: Reborn's writes for doll byte 0x2C. Do not edit by hand.", "return {"]
    for s, e in runs(a, b):
        lines.append('  {0x%08X, "%s"},' % (EWRAM + s, b[s:e + 1].hex()))
    lines.append("}")
    dst = ROOT / "tools/debug/partner.lua"
    dst.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(dst, len(lines) - 2, "runs")


if __name__ == "__main__":
    main()
